        hi = min(n, lo + CHUNK - 1)
        call ew_vv(op, hi - lo + 1, a(lo), b(lo), out(lo))
      end do
      !$omp end parallel do
    else
      call ew_vv(op, n, a, b, out)
    end if
  end subroutine numj_ew_contig

