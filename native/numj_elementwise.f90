  !> out = a op b over n-d strided operands (out disjoint from a and b).
  !> desc(nd, 4): column 1 = extents, columns 2.. = element strides of out, a, b;
  !> dim 1 is the innermost (fastest) axis. o* = element offset of the first logical element from the pointer.
  subroutine numj_ew_nd(op, nd, desc, out, oout, a, oa, b, ob, nthreads) bind(C, name='numj_ew_nd')
    integer(c_int), value :: nd, nthreads
    integer(c_int64_t), intent(in) :: desc(nd, 4)
    integer(c_int64_t), value :: oout, oa, ob
    integer(c_int), value :: op
    real(c_double), intent(inout) :: out(0:*)
    real(c_double), intent(in) :: a(0:*), b(0:*)
    integer(c_int64_t) :: nrows, r0, r1, chunk, t
    nrows = 1
    if (nd > 1) nrows = product(desc(2:nd, 1))
    if (nthreads > 1 .and. nrows > 1) then
      chunk = (nrows + nthreads - 1) / nthreads
      !$omp parallel do num_threads(nthreads) schedule(static, 1) private(r0, r1)
      do t = 0, nthreads - 1
        r0 = t * chunk
        r1 = min(nrows, r0 + chunk) - 1
        if (r0 <= r1) call rows(r0, r1)
      end do
      !$omp end parallel do
    else
      call rows(0_c_int64_t, nrows - 1)
    end if

  contains

    subroutine rows(r0, r1)
      integer(c_int64_t), intent(in) :: r0, r1
      integer(c_int64_t) :: r, pout, pa, pb, idx(nd)
      integer :: kk
      pout = oout + offset_of(r0, nd, desc(:, 1), desc(:, 2))
      pa = oa + offset_of(r0, nd, desc(:, 1), desc(:, 3))
      pb = ob + offset_of(r0, nd, desc(:, 1), desc(:, 4))
      call unravel_index(r0, nd, desc(:, 1), idx)
      do r = r0, r1
        call row_oop(op, desc(1, 1), out, pout, desc(1, 2), a, pa, desc(1, 3), b, pb, desc(1, 4))
        kk = 2
        do while (kk <= nd)
          idx(kk) = idx(kk) + 1
          pout = pout + desc(kk, 2)
          pa = pa + desc(kk, 3)
          pb = pb + desc(kk, 4)
          if (idx(kk) < desc(kk, 1)) exit
          pout = pout - desc(kk, 2) * desc(kk, 1)
          pa = pa - desc(kk, 3) * desc(kk, 1)
          pb = pb - desc(kk, 4) * desc(kk, 1)
          idx(kk) = 0
          kk = kk + 1
        end do
      end do
    end subroutine rows

  end subroutine numj_ew_nd

